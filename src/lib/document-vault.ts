import { decryptFile, encryptFile, keyRing, type KeyRing } from "@/lib/encryption";
import { documentStorageKey, DEFAULT_BUCKET, objectStore, type ObjectStore } from "@/lib/storage";

// The only way file bytes go in or out of storage. Encrypts on the way in,
// decrypts (and integrity-checks) on the way out. See src/lib/encryption.ts
// for the scheme and src/lib/storage.ts for where the ciphertext lands.
//
// No next/* and no Prisma: callers write the returned fields onto the Document
// row themselves, so the scripts can use this too.

export const FILE_ENCRYPTION = "AES-256-GCM/envelope-v1";

export type StoredDocument = {
  bucket: string;
  storageKey: string;
  encAlgorithm: string;
  encKeyId: string;
  encWrappedKey: string;
};

// Encrypts and uploads. The document id must be generated by the caller BEFORE
// this runs: it is bound into the ciphertext, so the row and the object can
// only ever be read together.
export async function storeDocumentBytes(
  input: { documentId: string; clientId: string; bytes: Buffer },
  options: { store?: ObjectStore; ring?: KeyRing } = {}
): Promise<StoredDocument> {
  const store = options.store ?? objectStore;
  const enc = encryptFile(input.bytes, input.documentId, options.ring ?? keyRing());
  const storageKey = documentStorageKey(input.clientId, input.documentId);
  await store.put(DEFAULT_BUCKET, storageKey, enc.body);
  return {
    bucket: DEFAULT_BUCKET,
    storageKey,
    encAlgorithm: FILE_ENCRYPTION,
    encKeyId: enc.keyId,
    encWrappedKey: enc.wrappedKey,
  };
}

export type DocumentRef = {
  id: string;
  bucket: string;
  storageKey: string;
  encKeyId: string | null;
  encWrappedKey: string | null;
};

export function isEncryptedDocument(doc: Pick<DocumentRef, "encKeyId" | "encWrappedKey">): boolean {
  return Boolean(doc.encKeyId && doc.encWrappedKey);
}

// Downloads and decrypts. Throws IntegrityError if the object was tampered
// with, truncated or swapped for another document's.
export async function readDocumentBytes(
  doc: DocumentRef,
  options: { store?: ObjectStore; ring?: KeyRing; allowLegacyPlaintext?: boolean } = {}
): Promise<Buffer> {
  const store = options.store ?? objectStore;
  const body = await store.get(doc.bucket, doc.storageKey);
  if (!isEncryptedDocument(doc)) {
    // Uploaded before encryption existed. Only the migration script is allowed
    // to read these; the app refuses to serve them until they're encrypted,
    // so "encrypted at rest" is a guarantee and not a mostly.
    if (options.allowLegacyPlaintext) return body;
    throw new LegacyPlaintextError();
  }
  return decryptFile(
    body,
    { documentId: doc.id, keyId: doc.encKeyId!, wrappedKey: doc.encWrappedKey! },
    options.ring ?? keyRing()
  );
}

export class LegacyPlaintextError extends Error {
  constructor() {
    super("This file was stored before encryption was turned on. An admin needs to run `npm run security:encrypt -- --apply`.");
  }
}
